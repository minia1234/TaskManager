    // 영어 값이 겹치면(예: "OK") 먼저 나온 한국어로 되돌린다.
    private static readonly Dictionary<string, string> Korean = English.GroupBy(kv => kv.Value).ToDictionary(g => g.Key, g => g.First().Key);

    public static bool IsEnglish { get; private set; }

    public static void Apply(string language)
    {
        IsEnglish = language == "en";
    }

    // 사전에 있는 문구만 바꾼다. 그 밖의 문구는 그대로 둔다.
    public static string Localize(string text)
    {
        if (IsEnglish)
        {
            return English.TryGetValue(text, out var en) ? en : text;
        }

        return Korean.TryGetValue(text, out var ko) ? ko : text;
    }

    // 자체 검증용: 영어 문구의 {n} 자리 표시자가 한국어 문구와 다른 항목. 다르면 영어로 쓸 때만 서식 오류가 난다.
    internal static List<string> PlaceholderMismatches()
    {
        static string Slots(string s) => string.Join(",", System.Text.RegularExpressions.Regex.Matches(s, @"\{(\d+)").Select(m => m.Groups[1].Value).Distinct().Order());
        return English.Where(kv => Slots(kv.Key) != Slots(kv.Value)).Select(kv => kv.Key).ToList();
    }

    // 한국어 기준 서식 문자열({0}, {1}...)을 현재 언어로 바꾼 뒤 채운다.
    public static string Fmt(string koreanTemplate, params object?[] args) =>
        string.Format(Localize(koreanTemplate), args);
